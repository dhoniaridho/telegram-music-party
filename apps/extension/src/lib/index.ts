function getPlayerVideoData(): any {
    const player = document.querySelector("#movie_player") as
        | (HTMLElement & { getVideoData?: () => any })
        | null;
    try {
        return player?.getVideoData?.() ?? null;
    } catch {
        return null;
    }
}

function getVideoElement() {
    return document.querySelector(
        "#movie_player > div.html5-video-container > video"
    ) as HTMLVideoElement | null;
}

function getVideoPlaybackState(video: HTMLVideoElement | null) {
    if (!video || video.ended) return "standby" as const;
    if (!video.paused) return "playing" as const;
    if (video.currentSrc || video.src || video.readyState > 0 || getVideoId()) {
        return "paused" as const;
    }
    return "standby" as const;
}

function getVideoId(): string | null {
    const playerVideoId = getPlayerVideoData()?.video_id;
    if (typeof playerVideoId === "string" && playerVideoId) return playerVideoId;

    const u = document
        .querySelector('[class="ytp-title-link yt-uix-sessionlink"]')
        ?.getAttribute("href");
    if (!u) return null;
    return new URL(u, window.location.origin).searchParams.get("v");
}

function getPlaybackState(): {
    song: string;
    artist: string;
    state: "playing" | "paused" | "standby";
    el: HTMLVideoElement;
} {
    const el = getVideoElement() as HTMLVideoElement;

    const song =
        document.querySelector(".title.ytmusic-player-bar")?.textContent?.trim() ||
        "Unknown title";

    const state = getVideoPlaybackState(el);
    if (state !== "standby") {
        return {
            song,
            artist: getCurrentArtist(),
            state,
            el,
        };
    }
    return {
        el: el as HTMLVideoElement,
        song,
        state: "standby",
        artist: "",
    };
}

type Queue = { id: string; url: string };
type NowPlaying = {
    videoId: string | null;
    title: string;
    artist: string;
    artwork: string | null;
};

function getNowPlaying(): NowPlaying | null {
    const video = getVideoElement();
    if (video?.ended) return null;

    const playerVideoData = getPlayerVideoData();
    const videoId =
        getVideoId() ||
        (typeof playerVideoData?.video_id === "string" ? playerVideoData.video_id : null) ||
        new URL(window.location.href).searchParams.get("v");
    const title =
        document.querySelector(".title.ytmusic-player-bar")?.textContent?.trim() ||
        (typeof playerVideoData?.title === "string" ? playerVideoData.title.trim() : "");
    if (!title) return null;

    return {
        videoId,
        title: title || "Unknown title",
        artist: getCurrentArtist(),
        artwork: videoId ? `https://img.youtube.com/vi/${videoId}/hqdefault.jpg` : null,
    };
}

function navigateToQueueItem(queue: Queue) {
    const currentUrl = new URL(window.location.href);
    if (currentUrl.searchParams.get("v") === queue.url) return false;

    const targetUrl = new URL("/watch", window.location.origin);
    targetUrl.searchParams.set("v", queue.url);
    targetUrl.searchParams.set("qid", queue.id);
    window.location.assign(targetUrl.toString());
    return true;
}

function getCurrentArtist(): string {
    const byline = document.querySelector(
        "ytmusic-player-bar yt-formatted-string.byline"
    );
    const bylineText =
        byline?.getAttribute("title") || byline?.textContent || "";
    const artistName = bylineText.split("•")[0]?.trim();
    if (artistName) return artistName;

    return byline?.querySelector("a")?.textContent?.trim() || "Unknown artist";
}

function play(queue?: Queue) {
    const playback = getPlaybackState();
    if (queue?.url && playback.state === "standby") {
        navigateToQueueItem(queue);
        return;
    }
    if (playback.state === "paused") {
        void playback.el.play().then(
            () => window.setTimeout(removeListParameter, 250),
            removeListParameter
        );
        return;
    }
    removeListParameter();
}

